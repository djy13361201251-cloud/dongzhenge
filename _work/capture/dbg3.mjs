import { spawn } from 'node:child_process';
const CHROME='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const PORT=9437;
const chrome=spawn(CHROME,['--headless=new','--disable-gpu','--no-sandbox','--hide-scrollbars','--window-size=1280,900','--remote-debugging-port='+PORT,'about:blank'],{stdio:'ignore'});
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
await sleep(2200);
const list=await (await fetch(`http://127.0.0.1:${PORT}/json/list`)).json();
const ws=new WebSocket(list[0].webSocketDebuggerUrl);
let id=0;const pend=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data); if(m.id&&pend.has(m.id)){pend.get(m.id)(m);pend.delete(m.id);}};
const send=(m,p={})=>new Promise(res=>{const i=++id;pend.set(i,res);ws.send(JSON.stringify({id:i,method:m,params:p}));});
await new Promise(r=>ws.onopen=r);
await send('Runtime.enable'); await send('Page.enable');
await send('Page.navigate',{url:'http://127.0.0.1:8899/index.html'});
await sleep(1500);
const ev=async x=>{const r=await send('Runtime.evaluate',{expression:x,returnByValue:true,awaitPromise:true});
  if(r.result?.exceptionDetails) return {__err:r.result.exceptionDetails.exception?.description};
  return r.result?.result?.value;};
console.log('before override:', await ev('innerWidth+"x"+innerHeight'));
await send('Emulation.setDeviceMetricsOverride',{width:1280,height:900,deviceScaleFactor:1,mobile:false});
await sleep(600);
console.log('after override:', await ev('innerWidth+"x"+innerHeight+" body="+document.body.clientWidth'));
await ev('window.dispatchEvent(new Event("resize"))');
await sleep(900);
console.log('after resize:', await ev('(function(){var cv=document.getElementById("cv");var r=cv.getBoundingClientRect();return innerWidth+"x"+innerHeight+" body="+document.body.clientWidth+" cv="+Math.round(r.width)+"x"+Math.round(r.height)})()'));
ws.close(); chrome.kill();
